//! Coverage inventory for the upstream snapshot, not a claim of verified parity.
//!
//! A listed Rust API means an initial implementation exists. Full behavioral,
//! visual, accessibility and example parity still requires independent review.

/// One supported upstream tag and its initial Rust mapping, if any.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PortEntry {
    pub upstream: &'static str,
    pub rust_api: Option<&'static str>,
    pub module: Option<&'static str>,
}

/// A mapping is not a statement of behavioral or visual parity.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PortMappingKind {
    Component,
    RenamedComponent,
    ItemModel,
    InternalIntegration,
    Composition,
    Unported,
}

impl PortMappingKind {
    pub const fn label(self) -> &'static str {
        match self {
            Self::Component => "Component",
            Self::RenamedComponent => "Renamed component",
            Self::ItemModel => "Item model",
            Self::InternalIntegration => "Internal integration",
            Self::Composition => "Composed API",
            Self::Unported => "Not ported",
        }
    }
}

impl PortEntry {
    /// Actual declared custom-element tag.
    pub fn upstream_tag(&self) -> Option<String> {
        match self.upstream {
            "ix-playground" => Some("ix-playground".into()),
            name => Some(format!("ix-{name}")),
        }
    }

    pub fn mapping_kind(&self) -> PortMappingKind {
        if self.rust_api.is_none() {
            return PortMappingKind::Unported;
        }
        match self.upstream {
            "select-item" | "tab-item" => PortMappingKind::ItemModel,
            "application-switch-modal" | "menu-expand-icon" => PortMappingKind::InternalIntegration,
            "group-context-menu" => PortMappingKind::Composition,
            "css-grid-item" => PortMappingKind::RenamedComponent,
            _ => PortMappingKind::Component,
        }
    }
}

